-- AI Meeting Notes / interaction-edit / trip-completion concurrency fix
-- (2026-10-21, fourth follow-up review). STAGING ONLY -- not applied to
-- Production as part of this round, same carve-out as drizzle/0046,
-- 0047, 0050, and 0051.
--
-- Closes a real atomicity bug confirmed in release candidate 62dec37:
-- saveConcurrentSummaryAndFollowUps (and the same shape in
-- applyInteractionEdit and completeProspectMeeting) ran its CAS'd
-- `interactions` UPDATE on its own, read back ITS OWN rowcount to prove
-- the CAS applied, then -- only once proven -- ran the dependent
-- follow-up/reminder/relationship-fact writes as a SEPARATE D1 batch.
-- That is two separate commits, not one transaction: when the second
-- batch's own write collides with different content (e.g. a follow-up
-- id already holds a different description), the function correctly
-- rejects the request, but the first batch's summary UPDATE had already
-- committed. A rejected save was leaving the interaction's new summary
-- permanently written.
--
-- The fix keeps the primary CAS'd write and every dependent write in ONE
-- `env.DB.batch()` call (one real SQLite transaction -- confirmed via
-- this repo's own D1SqliteAdapter, which wraps every batch in `BEGIN
-- IMMEDIATE` / `COMMIT`, rolling back and rethrowing on any statement
-- that throws). That alone is not sufficient: D1 batch statements run
-- unconditionally in sequence (there is no SQL-level "skip the rest if
-- the previous statement affected zero rows"), so a dependent write
-- still needs a WHERE-clause proof, evaluated at batch-execution time,
-- that THIS SPECIFIC request's own primary write is what actually
-- applied -- never inferred from matching final content (two unrelated
-- writes can coincidentally produce the same text) and never from a
-- bare `changes()` chained past an intervening statement (the SQL
-- `changes()` function only ever describes the immediately preceding
-- statement, so a second or third dependent statement reading it would
-- see the FIRST dependent statement's own rowcount, not the primary
-- write's).
--
-- `write_token` is that proof. Every CAS'd primary UPDATE now also
-- stamps a FRESH, request-unique value here (a crypto.randomUUID(), one
-- per write attempt, never reused and never shared with any other
-- request) as part of the SAME statement that applies the CAS. Every
-- dependent statement in the same batch is then gated on
-- `EXISTS (SELECT 1 FROM interactions WHERE id = ? AND write_token = ?)`
-- bound to that exact value. Because the token is a fresh random value
-- generated by THIS call and checked against nothing but itself, no
-- concurrent request -- even one racing from the exact same baseline --
-- can ever cause that EXISTS check to read true except as a direct
-- consequence of THIS request's own primary statement having matched
-- its CAS condition moments earlier, in the same transaction. A CAS
-- miss leaves `write_token` unchanged, so every dependent statement's
-- gate reads false and the whole request's companion writes are
-- correctly no-ops -- with no compensating/undo write ever needed,
-- because nothing partial was ever written to begin with.
--
-- A plain UPDATE/INSERT/DELETE cannot itself abort the rest of a D1
-- batch on a 0-row result (D1 batch only rolls back on a THROWN error),
-- so this migration does not by itself require a schema change beyond
-- this one column -- the actual rollback-on-genuine-conflict path (a
-- follow-up id already holding DIFFERENT content) is a real PRIMARY KEY
-- collision, produced deliberately by pairing a content-matching-gated
-- DELETE with a write_token-gated INSERT of the same id (see
-- lib/meeting-notes/concurrent-save.ts) -- an existing SQLite mechanism
-- already relied on elsewhere in this codebase for exactly this
-- "collision throws, D1 batch rolls back the whole request" guarantee.
--
-- Nullable, no default needed beyond SQLite's own NULL default -- every
-- existing row simply starts with no token, identical in meaning to
-- "never written under this scheme yet." SQLite's ALTER TABLE ADD COLUMN
-- is an in-place metadata change here (no table rebuild, no existing row
-- touched), exactly like the corresponding ADD COLUMN statements across
-- drizzle/0045-0047 and 0050.
ALTER TABLE `interactions` ADD COLUMN `write_token` text;
